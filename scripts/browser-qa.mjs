// Optional QA driver: npm install --no-save playwright-core
// Use an existing Chromium installation; no browser download is required.
import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE||'playwright-core');
const browser=await chromium.launch({executablePath:process.env.PLAYWRIGHT_CHROMIUM_PATH||'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
const artifacts=process.env.QA_ARTIFACTS||'/tmp/eleven-zero-zero-qa/screenshots';
await mkdir(artifacts,{recursive:true});
const url=process.env.QA_URL||'http://localhost:4173';
const errors=[];
try {
  const context=await browser.newContext({viewport:{width:1440,height:1100},permissions:['clipboard-read','clipboard-write']});
  const page=await context.newPage();
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(url);await page.evaluate(()=>document.fonts.ready);
  assert.equal(await page.title(),'11–0–0 · The Fantasy Chess Olympiad');
  await page.screenshot({path:`${artifacts}/desktop-draft.png`,fullPage:true});
  await page.getByRole('button',{name:'How to play'}).click();
  await page.getByRole('dialog').waitFor({state:'visible'});
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('dialog').isVisible(),false);
  await page.getByRole('button',{name:'Rename team'}).click();
  await page.getByLabel('TEAM NAME',{exact:true}).fill('Queensland Knights');
  await page.getByRole('button',{name:'Save team name'}).click();
  await page.getByRole('button',{name:'Expert Trust your instincts'}).click();
  await page.getByRole('button',{name:'Classic Ratings visible'}).click();
  await page.getByRole('button',{name:'Select reserve for your next pick'}).click();
  await page.getByRole('button',{name:'Spin a nation'}).click();
  await page.locator('.candidate').first().waitFor();
  const firstOffer=await page.locator('.nation-code').textContent();
  assert.ok(firstOffer.length===3);
  await page.getByRole('button',{name:'Reroll nation'}).click();
  await page.waitForFunction(()=>document.querySelector('.reroll-button')?.textContent.includes('1 left'));
  assert.ok((await page.getByRole('button',{name:'Reroll nation'}).textContent()).includes('1 left'));
  await page.screenshot({path:`${artifacts}/desktop-offer.png`,fullPage:true});
  await page.locator('.candidate').first().click();
  assert.ok(await page.locator('.reserve-slot').evaluate(el=>el.classList.contains('filled')));
  await page.reload();
  assert.equal(await page.locator('.squad-slot.filled').count(),1);
  assert.ok((await page.getByRole('button',{name:'Rename team'}).textContent()).includes('Queensland Knights'));
  for(let i=1;i<5;i++){
    await page.getByRole('button',{name:'Spin a nation'}).click();
    await page.locator('.candidate').first().click();
  }
  assert.equal(await page.locator('.squad-slot.filled').count(),5);
  await page.getByRole('button',{name:'Enter the Olympiad'}).click();
  await page.getByRole('button',{name:'Play round 1'}).click();
  await page.locator('.match-score').waitFor();
  assert.equal(await page.locator('.board-result').count(),4);
  await page.getByRole('button',{name:'Rotate reserve'}).click();
  await page.locator('.rotation-option').first().click();
  await page.getByRole('button',{name:'Play round 2'}).click();
  await page.getByRole('button',{name:'Play round 3'}).waitFor();
  await page.getByRole('button',{name:/Round 1, /}).click();
  assert.ok((await page.locator('.match-heading').textContent()).includes('ROUND 01'));
  await page.getByRole('button',{name:'Full standings',exact:true}).click();
  assert.equal(await page.locator('.standings-row.full').count(),32);
  await page.getByRole('button',{name:'Your matches',exact:true}).click();
  await page.screenshot({path:`${artifacts}/desktop-tournament.png`,fullPage:true});
  await page.reload();
  await page.getByRole('button',{name:'Play round 3'}).waitFor();
  await page.getByRole('button',{name:'Simulate remaining rounds'}).click();
  await page.getByRole('button',{name:'Copy result'}).waitFor();
  assert.equal(await page.locator('.round-tabs button:not([disabled])').count(),11);
  await page.getByRole('button',{name:'Copy result'}).click();
  const copied=await page.evaluate(()=>navigator.clipboard.readText());
  assert.ok(copied.includes('Queensland Knights'));
  await page.screenshot({path:`${artifacts}/desktop-results.png`,fullPage:true});
  await page.getByRole('button',{name:'Build another team'}).click();
  await page.getByRole('button',{name:'Keep my team'}).click();
  assert.ok(await page.getByRole('button',{name:'Copy result'}).isVisible());
  await page.getByRole('button',{name:'Build another team'}).click();
  await page.getByRole('button',{name:'Start a new draft'}).click();
  assert.equal(await page.locator('.squad-slot.filled').count(),0);
  // Expert and auto-draft paths, plus mobile layout and a full playthrough.
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'Expert Trust your instincts'}).click();
  await page.getByRole('button',{name:'Spin a nation'}).click();
  await page.locator('.candidate').first().waitFor();
  assert.ok((await page.locator('.candidate-rating').first().textContent()).includes('????'));
  await page.screenshot({path:`${artifacts}/mobile-draft.png`,fullPage:true});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
  await page.getByRole('button',{name:'Quick draft'}).click();
  assert.equal(await page.locator('.squad-slot.filled').count(),5);
  await page.getByRole('button',{name:'Enter the Olympiad'}).click();
  await page.getByRole('button',{name:'Simulate remaining rounds'}).click();
  await page.getByRole('button',{name:'Copy result'}).waitFor();
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
  await page.getByRole('button',{name:'Full standings',exact:true}).click();
  assert.equal(await page.locator('.standings-row.full').count(),32);
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
  await page.getByRole('button',{name:'Your matches',exact:true}).click();
  await page.screenshot({path:`${artifacts}/mobile-results.png`,fullPage:true});
  await page.setViewportSize({width:320,height:740});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
  assert.deepEqual(errors,[]);
  console.log('Browser QA passed: manual and quick drafts, expert mode, rerolls, team name, board targeting, persistence, reserve rotation, rounds, standings, sharing, reset, and 320/390/1440px layouts.');
  console.log(`Screenshots: ${artifacts}`);
} finally {await browser.close();}
